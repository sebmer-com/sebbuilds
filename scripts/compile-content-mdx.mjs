import { createHash } from "node:crypto";
import { watch } from "node:fs";
import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { compile } from "@mdx-js/mdx";
import remarkGfm from "remark-gfm";

const repositoryDirectory = fileURLToPath(new URL("../", import.meta.url));
const collectionKinds = ["projects", "research"];
const generatedHeader = "// Generated by scripts/compile-content-mdx.mjs.\n";
const activeWatchers = new Map();
let writeSequence = 0;

function contentOnlyMdx() {
  return (tree, file) => {
    function visit(node) {
      if (["mdxjsEsm", "mdxFlowExpression", "mdxTextExpression"].includes(node.type)) {
        file.fail("Authored JavaScript is not supported in content MDX", node);
      }
      for (const attribute of node.attributes ?? []) {
        if (
          attribute.type === "mdxJsxExpressionAttribute" ||
          attribute.value?.type === "mdxJsxAttributeValueExpression"
        ) {
          file.fail("Authored JavaScript is not supported in content MDX", attribute);
        }
      }
      for (const child of node.children ?? []) visit(child);
    }
    visit(tree);
  };
}

function directories({ rootDirectory = repositoryDirectory, outputDirectory } = {}) {
  const root = path.resolve(rootDirectory);
  return {
    rootDirectory: root,
    outputDirectory: path.resolve(outputDirectory ?? path.join(root, "src/generated/mdx")),
  };
}

async function readEntries(rootDirectory) {
  const entries = [];
  const fingerprint = createHash("sha256");
  for (const kind of collectionKinds) {
    const collectionDirectory = await fs.realpath(path.join(rootDirectory, "public/content", kind));
    const manifestBytes = await fs.readFile(path.join(collectionDirectory, "index.json"));
    fingerprint.update(`${kind}/index.json\0`).update(manifestBytes);
    const manifest = JSON.parse(manifestBytes.toString("utf8"));
    if (!Array.isArray(manifest.items)) throw new Error(`Invalid ${kind} manifest items`);
    const files = new Set();
    const slugs = new Set();
    for (const item of manifest.items) {
      if (typeof item !== "string" || !/^[a-z0-9][a-z0-9.-]*$/.test(item)) {
        throw new Error(`Invalid ${kind} manifest filename`);
      }
      const filename = item.endsWith(".json") ? item : `${item}.json`;
      if (files.has(filename)) throw new Error(`Duplicate ${kind} manifest filename: ${filename}`);
      files.add(filename);
      const sourcePath = await fs.realpath(path.join(collectionDirectory, filename));
      if (path.dirname(sourcePath) !== collectionDirectory) {
        throw new Error(`Invalid ${kind} manifest path`);
      }
      const sourceBytes = await fs.readFile(sourcePath);
      fingerprint.update(`${kind}/${filename}\0`).update(sourceBytes);
      const source = JSON.parse(sourceBytes.toString("utf8"));
      if (typeof source.slug !== "string" || !/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(source.slug)) {
        throw new Error(`Invalid ${kind} content slug`);
      }
      if (slugs.has(source.slug)) throw new Error(`Duplicate ${kind} slug: ${source.slug}`);
      slugs.add(source.slug);
      if (typeof source.body !== "string" || source.body.trim() === "") {
        throw new Error(`Missing ${kind}/${filename} body`);
      }
      entries.push({
        kind,
        slug: source.slug,
        body: source.body,
        sourceName: `${kind}/${filename}`,
        modulePath: `${kind}/${source.slug}.mjs`,
        bodySha256: createHash("sha256").update(source.body).digest("hex"),
      });
    }
  }
  return { entries, fingerprint: fingerprint.digest("hex") };
}

async function replaceChangedFile(filename, contents) {
  try {
    if ((await fs.readFile(filename, "utf8")) === contents) return false;
  } catch (error) {
    if (error.code !== "ENOENT") throw error;
  }
  await fs.mkdir(path.dirname(filename), { recursive: true });
  const temporaryFile = `${filename}.tmp-${process.pid}-${writeSequence++}`;
  try {
    await fs.writeFile(temporaryFile, contents, { flag: "wx" });
    await fs.rename(temporaryFile, filename);
  } finally {
    await fs.rm(temporaryFile, { force: true });
  }
  return true;
}

async function removeStaleModules(outputDirectory, expectedFiles) {
  let changed = false;
  for (const kind of collectionKinds) {
    const directory = path.join(outputDirectory, kind);
    let files;
    try {
      files = await fs.readdir(directory, { withFileTypes: true });
    } catch (error) {
      if (error.code === "ENOENT") continue;
      throw error;
    }
    for (const file of files) {
      const relativePath = `${kind}/${file.name}`;
      if (!file.isFile() || !file.name.endsWith(".mjs") || expectedFiles.has(relativePath)) continue;
      const filename = path.join(directory, file.name);
      if (!(await fs.readFile(filename, "utf8")).startsWith(generatedHeader)) continue;
      await fs.unlink(filename);
      changed = true;
    }
  }
  return changed;
}

export async function compileContentMdx(options) {
  const { rootDirectory, outputDirectory } = directories(options);
  const { entries, fingerprint } = await readEntries(rootDirectory);
  // Validate and compile the complete collection before replacing any successful output.
  const modules = await Promise.all(entries.map(async (entry) => {
    const result = await compile({ value: entry.body, path: entry.sourceName }, {
      outputFormat: "program",
      jsx: false,
      development: false,
      remarkPlugins: [...(entry.kind === "research" ? [remarkGfm] : []), contentOnlyMdx],
    });
    return `${generatedHeader}// Source: ${entry.sourceName}; body SHA256: ${entry.bodySha256}\n${String(result)}`;
  }));
  const imports = entries.map((entry, index) => `import Content${index} from ${JSON.stringify(`./${entry.modulePath}`)};`);
  const collections = collectionKinds.map((kind) => {
    const members = entries.flatMap((entry, index) => entry.kind === kind
      ? [`    ${JSON.stringify(entry.slug)}: Content${index},`]
      : []);
    return `  ${kind}: Object.freeze({\n${members.join("\n")}\n  }),`;
  });
  const registry = `${generatedHeader}// Canonical source SHA256: ${fingerprint}\n${imports.join("\n")}\n\nexport const compiledMdx = Object.freeze({\n${collections.join("\n")}\n});\n`;
  let changed = false;
  for (let index = 0; index < entries.length; index++) {
    if (await replaceChangedFile(path.join(outputDirectory, entries[index].modulePath), modules[index])) changed = true;
  }
  if (await replaceChangedFile(path.join(outputDirectory, "index.mjs"), registry)) changed = true;
  if (await removeStaleModules(outputDirectory, new Set(entries.map((entry) => entry.modulePath)))) changed = true;
  return {
    changed,
    entries: entries.map(({ kind, slug, modulePath, bodySha256 }) => ({ kind, slug, modulePath, bodySha256 })),
  };
}

export function watchContentMdx(options) {
  const resolved = directories(options);
  const key = `${resolved.rootDirectory}\0${resolved.outputDirectory}`;
  if (activeWatchers.has(key)) return activeWatchers.get(key);
  let timer;
  let running = false;
  let pending = false;
  let closed = false;

  async function rebuild() {
    if (running) { pending = true; return; }
    running = true;
    do {
      pending = false;
      try {
        await compileContentMdx(resolved);
      } catch (error) {
        console.error(`[content-mdx] ${error.message}`);
      }
    } while (pending && !closed);
    running = false;
  }

  const watchers = collectionKinds.map((kind) => watch(
    path.join(resolved.rootDirectory, "public/content", kind),
    { persistent: false },
    (_event, filename) => {
      if (closed || (filename && !filename.toString().endsWith(".json"))) return;
      clearTimeout(timer);
      timer = setTimeout(() => { if (!closed) void rebuild(); }, 80);
      timer.unref();
    },
  ));
  const handle = {
    close() {
      closed = true;
      clearTimeout(timer);
      for (const watcher of watchers) watcher.close();
      activeWatchers.delete(key);
    },
  };
  activeWatchers.set(key, handle);
  return handle;
}
